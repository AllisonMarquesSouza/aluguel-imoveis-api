CREATE TABLE quadra
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loteamento_id  INTEGER     NOT NULL,
    identificacao  VARCHAR(50) NOT NULL,

    CONSTRAINT fk_quadra_loteamento
        FOREIGN KEY (loteamento_id)
            REFERENCES loteamento (id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT uq_quadra_loteamento_identificacao
        UNIQUE (loteamento_id, identificacao),

    CONSTRAINT ck_quadra_identificacao
        CHECK (length(trim(identificacao)) > 0)
);
