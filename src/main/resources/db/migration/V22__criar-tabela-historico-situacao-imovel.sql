CREATE TABLE historico_situacao_imovel
(
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imovel_id          INTEGER     NOT NULL,
    usuario_id         INTEGER     NOT NULL,
    situacao_anterior  VARCHAR(20) NOT NULL,
    situacao_nova      VARCHAR(20) NOT NULL,
    observacao         TEXT        NOT NULL,
    alterado_em        TIMESTAMP   NOT NULL,

    CONSTRAINT fk_historico_situacao_imovel_imovel
        FOREIGN KEY (imovel_id)
            REFERENCES imovel (id)
            ON UPDATE CASCADE
            ON DELETE CASCADE,

    CONSTRAINT fk_historico_situacao_imovel_usuario
        FOREIGN KEY (usuario_id)
            REFERENCES usuario (id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT ck_historico_situacao_imovel_anterior
        CHECK (situacao_anterior IN ('DISPONIVEL', 'RESERVADO', 'VENDIDO', 'ALUGADO')),

    CONSTRAINT ck_historico_situacao_imovel_nova
        CHECK (situacao_nova IN ('DISPONIVEL', 'RESERVADO', 'VENDIDO', 'ALUGADO')),

    CONSTRAINT ck_historico_situacao_imovel_transicao
        CHECK (situacao_anterior <> situacao_nova),

    CONSTRAINT ck_historico_situacao_imovel_observacao
        CHECK (length(trim(observacao)) > 0)
);
