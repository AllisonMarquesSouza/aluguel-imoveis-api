CREATE TABLE contato_imovel
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imovel_id   INTEGER     NOT NULL,
    corretor_id INTEGER     NOT NULL,
    canal       VARCHAR(20) NOT NULL,
    criado_em   TIMESTAMP   NOT NULL,
    retorno     VARCHAR(20),

    CONSTRAINT fk_contato_imovel_imovel
        FOREIGN KEY (imovel_id)
            REFERENCES imovel (id)
            ON UPDATE CASCADE
            ON DELETE CASCADE,

    CONSTRAINT fk_contato_imovel_corretor
        FOREIGN KEY (corretor_id)
            REFERENCES corretor (usuario_id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT ck_contato_imovel_canal
        CHECK (canal IN ('WHATSAPP', 'TELEFONE', 'EMAIL')),

    CONSTRAINT ck_contato_imovel_retorno
        CHECK (retorno IS NULL OR retorno IN ('FALEI', 'VISITA_AGENDADA', 'SEM_RESPOSTA', 'DESCARTADO'))
);

CREATE INDEX ix_contato_imovel_corretor_criado_em
    ON contato_imovel (corretor_id, criado_em);

CREATE INDEX ix_contato_imovel_imovel_criado_em
    ON contato_imovel (imovel_id, criado_em);
