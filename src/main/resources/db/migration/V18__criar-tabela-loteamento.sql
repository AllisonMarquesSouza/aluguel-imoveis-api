CREATE TABLE loteamento
(
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id          INTEGER     NOT NULL,
    cidade_id           INTEGER     NOT NULL,
    nome                VARCHAR(180) NOT NULL,
    incorporadora       VARCHAR(180) NOT NULL,
    asfalto             BOOLEAN     NOT NULL,
    agua                BOOLEAN     NOT NULL,
    energia             BOOLEAN     NOT NULL,
    esgoto              BOOLEAN     NOT NULL,
    iluminacao_publica  BOOLEAN     NOT NULL,
    areas_lazer         TEXT,

    CONSTRAINT fk_loteamento_empresa
        FOREIGN KEY (empresa_id)
            REFERENCES empresa (id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT fk_loteamento_cidade
        FOREIGN KEY (cidade_id)
            REFERENCES cidade (id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT ck_loteamento_nome
        CHECK (length(trim(nome)) > 0),

    CONSTRAINT ck_loteamento_incorporadora
        CHECK (length(trim(incorporadora)) > 0)
);
