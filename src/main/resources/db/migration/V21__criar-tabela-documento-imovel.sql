CREATE TABLE documento_imovel
(
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imovel_id        INTEGER      NOT NULL,
    tipo             VARCHAR(30)  NOT NULL,
    nome_arquivo     VARCHAR(255) NOT NULL,
    arquivo_id       VARCHAR(36)  NOT NULL UNIQUE,
    data_documento   DATE         NOT NULL,
    criado_em        TIMESTAMP    NOT NULL,

    CONSTRAINT fk_documento_imovel_imovel
        FOREIGN KEY (imovel_id)
            REFERENCES imovel (id)
            ON UPDATE CASCADE
            ON DELETE CASCADE,

    CONSTRAINT uq_documento_imovel_tipo
        UNIQUE (imovel_id, tipo),

    CONSTRAINT ck_documento_imovel_tipo
        CHECK (tipo IN ('MATRICULA', 'CARNE_IPTU', 'AUTORIZACAO_PROPRIETARIO')),

    CONSTRAINT ck_documento_imovel_nome_arquivo
        CHECK (length(trim(nome_arquivo)) > 0)
);
