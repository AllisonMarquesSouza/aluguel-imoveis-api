CREATE TABLE predio
(
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id            INTEGER        NOT NULL,
    nome                  VARCHAR(180)   NOT NULL,
    cep                   VARCHAR(8)     NOT NULL,
    logradouro            VARCHAR(180)   NOT NULL,
    numero                VARCHAR(20)    NOT NULL,
    complemento           VARCHAR(100),
    bairro                VARCHAR(100)   NOT NULL,
    cidade_id             INTEGER        NOT NULL,
    latitude              NUMERIC(10, 8) NOT NULL,
    longitude             NUMERIC(11, 8) NOT NULL,
    numero_andares        INTEGER        NOT NULL,
    unidades_por_andar    INTEGER        NOT NULL,
    ano_construcao        INTEGER        NOT NULL,
    elevadores            INTEGER        NOT NULL,
    portaria_24h          BOOLEAN        NOT NULL,
    piscina               BOOLEAN        NOT NULL,
    academia              BOOLEAN        NOT NULL,
    salao_festas          BOOLEAN        NOT NULL,
    playground            BOOLEAN        NOT NULL,
    valor_condominio_base NUMERIC(15, 2) NOT NULL,

    CONSTRAINT fk_predio_empresa
        FOREIGN KEY (empresa_id)
            REFERENCES empresa (id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT fk_predio_cidade
        FOREIGN KEY (cidade_id)
            REFERENCES cidade (id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT ck_predio_numero_andares
        CHECK (numero_andares > 0),

    CONSTRAINT ck_predio_unidades_por_andar
        CHECK (unidades_por_andar > 0),

    CONSTRAINT ck_predio_ano_construcao
        CHECK (ano_construcao >= 0),

    CONSTRAINT ck_predio_elevadores
        CHECK (elevadores >= 0),

    CONSTRAINT ck_predio_condominio_base
        CHECK (valor_condominio_base >= 0),

    CONSTRAINT ck_predio_cep
        CHECK (cep ~ '^[0-9]{8}$'),

    CONSTRAINT ck_predio_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT ck_predio_longitude
        CHECK (longitude BETWEEN -180 AND 180)
);
