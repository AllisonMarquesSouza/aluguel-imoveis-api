CREATE TABLE imovel
(
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(50)  NOT NULL,
    titulo           VARCHAR(180) NOT NULL,

    empresa_id       INTEGER      NOT NULL,
    corretor_id      INTEGER      NOT NULL,
    proprietario_id  INTEGER      NOT NULL,

    finalidade       VARCHAR(20)  NOT NULL,

    valor_venda      NUMERIC(15, 2),
    valor_aluguel    NUMERIC(15, 2),
    valor_condominio NUMERIC(15, 2),
    valor_iptu       NUMERIC(15, 2),

    descricao        TEXT,

    CONSTRAINT uq_imovel_empresa_codigo
        UNIQUE (empresa_id, codigo),

    CONSTRAINT fk_imovel_empresa
        FOREIGN KEY (empresa_id)
            REFERENCES empresa (id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT fk_imovel_corretor
        FOREIGN KEY (corretor_id)
            REFERENCES corretor (usuario_id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT fk_imovel_proprietario
        FOREIGN KEY (proprietario_id)
            REFERENCES proprietario (id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT,

    CONSTRAINT ck_imovel_finalidade
        CHECK (
            finalidade IN (
                           'VENDA',
                           'ALUGUEL',
                           'VENDA_E_ALUGUEL'
                )
            )
);
